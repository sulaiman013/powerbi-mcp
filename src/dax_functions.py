CATEGORIES: Dict[str, FrozenSet[str]] = {k: frozenset(v.split()) for k, v in _CATEGORIES.items()}
FUNCTIONS: FrozenSet[str] = frozenset().union(*CATEGORIES.values())

_INFO_VIEW = frozenset(n for n in CATEGORIES["info"] if n.startswith("INFO.VIEW."))

# Functions that evaluate an argument once per row of a table. A CALCULATE inside one of these
# is a deliberate context transition, not an accidental nesting.
ITERATORS: FrozenSet[str] = frozenset(
    {n for n in FUNCTIONS if n.endswith("X") and n not in ("INDEX", "MAX")}
    | {"PERCENTILEX.INC", "PERCENTILEX.EXC", "STDEVX.S", "STDEVX.P", "VARX.S", "VARX.P",
       "FILTER", "ADDCOLUMNS", "SELECTCOLUMNS", "GENERATE", "GENERATEALL", "SUMMARIZE", "GROUPBY",
       "TOPN", "SAMPLE", "FIRSTNONBLANK", "LASTNONBLANK", "FIRSTNONBLANKVALUE", "LASTNONBLANKVALUE",
       "GENERATESERIES", "WINDOW", "OFFSET", "ROWNUMBER", "RANK"})

# Aggregation functions that read a column (or a table) in the current filter context.
AGGREGATORS: FrozenSet[str] = frozenset(
    CATEGORIES["aggregation"] | {"MEDIAN", "MEDIANX", "GEOMEAN", "GEOMEANX", "STDEV.S", "STDEV.P",
                                 "VAR.S", "VAR.P", "PERCENTILE.INC", "PERCENTILE.EXC", "CONCATENATEX"})


def is_known_function(name: str) -> bool:
    """True when ``name`` is a DAX function.

    The INFO.* family mirrors the engine's schema rowsets and gains members with most releases,
    so any INFO.<Name> is accepted; INFO.VIEW.* is a fixed set of four and is checked exactly.
    """
    up = (name or "").upper()
    if up in FUNCTIONS:
        return True
    if up.startswith("INFO.VIEW."):
        return up in _INFO_VIEW
    if up.startswith("INFO.") and len(up) > 5:
        rest = up[5:]
        return rest.replace("_", "").isalnum()
    return False
